/*-------------------------------------------------------------------------
 *
 * parser_pushparse.c
 *	  Track B: drive PostgreSQL's SQL grammar with Lime's runtime push
 *	  parser over a ParserSnapshot, dispatching the base grammar's reduce
 *	  actions through the generated host-reduce wrapper (base_yyHostReduce,
 *	  emitted by `lime -n --host-reduce`).  This builds a real raw parse
 *	  tree in-process -- no subprocess, no C compiler.
 *
 * Isolated in its own translation unit because it includes Lime's
 * runtime headers via the <lime/...> path; that include directory is
 * confined here so the rest of the backend keeps PostgreSQL's own
 * headers (e.g. utils/snapshot.h, whose basename collides with Lime's).
 *
 * The composed ParserSnapshot (base grammar + any registered runtime
 * extensions) is supplied by parser_extension.c; this file only knows
 * how to feed the core scanner's token stream to a snapshot and recover
 * the resulting parse tree.
 *
 * Portions Copyright (c) 1996-2026, PostgreSQL Global Development Group
 * Portions Copyright (c) 1994, Regents of the University of California
 *
 * src/backend/parser/parser_pushparse.c
 *
 *-------------------------------------------------------------------------
 */
#include "postgres.h"

#include "gramparse.h"
#include "parser/parser.h"
#include "parser/scanner.h"

#include <lime/parse_context.h>
#include <lime/snapshot.h>

/*
 * Generated by `lime -j -n --host-reduce` into gram_snapshot.c / gram.c.
 *   base_yyBuildSnapshot()  -- ParserSnapshot from the backend parser
 *                              tables, with snap->host_reduce wired to
 *                              base_yyHostReduce and the grammar source
 *                              embedded for in-process recomposition.
 *   base_yyHostReduce()     -- runs the static yy_rule_reduce_fn[ruleno]
 *                              with a stack yyParser whose yyscanner is
 *                              the host_reduce `user` pointer.
 */
extern ParserSnapshot *base_yyBuildSnapshot(void);
extern int	base_yyHostReduce(void *user, int ruleno,
							  const void *rhs_values, const int *rhs_locs,
							  int nrhs, void *lhs_out, int *lhs_loc_out);

extern bool raw_parser_lime_pushparse(core_yyscan_t yyscanner,
									  base_yy_extra_type *yyextra,
									  List **result);

/*
 * The base snapshot, built once per backend on first use.  When grammar
 * extensions are active this will be replaced by the composed snapshot
 * (parser_extension.c); for now it is the base grammar only.
 */
static ParserSnapshot *base_snapshot = NULL;

/*
 * raw_parser_lime_pushparse
 *	  Parse `str` by driving the Lime push parser over the (base or
 *	  composed) ParserSnapshot.  On success stores the parse-tree List in
 *	  *result and returns true; on a syntax error returns false with
 *	  *result = NIL (matching base_yyparse's NIL-on-error contract).
 *
 * The caller (raw_parser) owns scanner setup/teardown and lookahead-mode
 * initialization, exactly as for the pull-parser path.
 */
bool
raw_parser_lime_pushparse(core_yyscan_t yyscanner,
						  base_yy_extra_type *yyextra,
						  List **result)
{
	ParseContext *ctx;
	int			rc = 0;
	void	   *tree;

	*result = NIL;

	if (base_snapshot == NULL)
	{
		base_snapshot = base_yyBuildSnapshot();
		if (base_snapshot == NULL)
			elog(ERROR, "could not build base parser snapshot");
	}

	/*
	 * Borrow the snapshot: it lives for the backend's lifetime, far longer
	 * than this parse, so we skip the per-parse refcount atomics.
	 */
	ctx = parse_begin_borrowed(base_snapshot);
	if (ctx == NULL)
		elog(ERROR, "could not begin parse");

	/*
	 * Route base-rule reduces to the generated host-reduce wrapper, passing
	 * the live scanner so %extra_argument (yyscanner) is available to every
	 * action.  (Extension-rule reduces will route to their LimeReduceFns
	 * once the composed snapshot is in use.)
	 */
	parse_set_host_reduce(ctx, base_yyHostReduce, yyscanner);

	for (;;)
	{
		YYSTYPE		lval;
		YYLTYPE		lloc = 0;
		int			tok;
		void	   *boxed;

		tok = base_yylex(&lval, &lloc, yyscanner);

		/*
		 * PostgreSQL's YYSTYPE is a union of pointer-width members.  The
		 * push parser stores one pointer-width payload per token and hands
		 * it to the base action as the matching $N; box the union's
		 * pointer payload.
		 */
		memcpy(&boxed, &lval, sizeof(void *));

		rc = parse_token(ctx, tok, boxed, lloc);

		if (tok == 0)			/* EOF: parse settles on this call */
			break;
		if (rc != 0)			/* syntax error */
			break;
	}

	if (rc == 0)
	{
		tree = parse_result(ctx);
		/* The start-rule action assigns yyextra->parsetree; prefer it. */
		*result = yyextra->parsetree;
		(void) tree;
	}

	parse_end(ctx);
	return (rc == 0);
}

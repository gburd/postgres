/*
 * The empty object is the concat identity on both sides: A || '{}' and
 * '{}' || A must each equal A.  '{}' adds no keys and conflicts on none, so it
 * cannot change the merged value from either direction.
 */
PG_PROP(concat_empty_identity)
{
	pg_prop_conn *conn;
	char	   *err = NULL;
	int			na = (int) pg_prop_draw_int(tc, 0, 4);
	StringInfoData a,
				q;

	conn = pg_prop_connect(&err);
	if (conn == NULL)
		pg_prop_fail(tc, "connect failed: %s", err ? err : "");

	initStringInfo(&a);
	draw_obj(tc, &a, na);

	initStringInfo(&q);
	appendStringInfo(&q,
					 "SELECT (%s || '{}'::jsonb) IS NOT DISTINCT FROM %s "
					 "AND ('{}'::jsonb || %s) IS NOT DISTINCT FROM %s",
					 a.data, a.data, a.data, a.data);

	require_true(tc, conn, q.data);

	pfree(a.data);
	pfree(q.data);
	pg_prop_disconnect(conn);
}

/*
 * Deleting an array element by index shrinks the array by one: for an array of
 * n elements (n in 1..6) and an index i in 0..n-1, (arr - i) has length n - 1.
 * (arr - int deletes the element at that index.)  Element identity after a
 * delete is fiddly in the presence of duplicate values, so this checks length
 * only.
 */
PG_PROP(array_delete_index)
{
	pg_prop_conn *conn;
	char	   *err = NULL;
	int			n = (int) pg_prop_draw_int(tc, 1, 6);
	int			i = (int) pg_prop_draw_int(tc, 0, n - 1);
	StringInfoData arr,
				q;

	conn = pg_prop_connect(&err);
	if (conn == NULL)
		pg_prop_fail(tc, "connect failed: %s", err ? err : "");

	initStringInfo(&arr);
	appendStringInfoString(&arr, "'[");
	for (int e = 0; e < n; e++)
	{
		StringInfoData v;

		if (e > 0)
			appendStringInfoChar(&arr, ',');
		initStringInfo(&v);
		draw_value(tc, &v);
		appendStringInfoString(&arr, v.data);
		pfree(v.data);
	}
	appendStringInfoString(&arr, "]'::jsonb");

	initStringInfo(&q);
	appendStringInfo(&q, "SELECT jsonb_array_length(%s - %d) = %d",
					 arr.data, i, n - 1);

	require_true(tc, conn, q.data);

	pfree(arr.data);
	pfree(q.data);
	pg_prop_disconnect(conn);
}

/*
 * Path delete removes a nested key: for J = {"k0": {"k1": V}}, J #- '{k0,k1}'
 * removes the inner key, so (J #- '{k0,k1}') #> '{k0}' is the empty object.
 * J is built so k0 maps to a single-key object {"k1": V}.
 */
PG_PROP(path_delete_removes_nested)
{
	pg_prop_conn *conn;
	char	   *err = NULL;
	StringInfoData v,
				j,
				q;

	conn = pg_prop_connect(&err);
	if (conn == NULL)
		pg_prop_fail(tc, "connect failed: %s", err ? err : "");

	initStringInfo(&v);
	draw_value(tc, &v);

	initStringInfo(&j);
	appendStringInfo(&j, "'{\"k0\":{\"k1\":%s}}'::jsonb", v.data);

	initStringInfo(&q);
	appendStringInfo(&q,
					 "SELECT ((%s #- '{k0,k1}') #> '{k0}') "
					 "IS NOT DISTINCT FROM '{}'::jsonb",
					 j.data);

	require_true(tc, conn, q.data);

	pfree(v.data);
	pfree(j.data);
	pfree(q.data);
	pg_prop_disconnect(conn);
}

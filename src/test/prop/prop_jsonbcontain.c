/*
 * Concat preserves the right operand under containment: (A || B) @> B always.
 * || is a right-wins top-level merge, so every key of B survives with B's
 * value in A || B; therefore the result must contain B.
 */
PG_PROP(concat_contains_operands)
{
	pg_prop_conn *conn;
	char	   *err = NULL;
	int			na = (int) pg_prop_draw_int(tc, 1, 4);
	int			nb = (int) pg_prop_draw_int(tc, 1, 4);
	StringInfoData a,
				b,
				q;

	conn = pg_prop_connect(&err);
	if (conn == NULL)
		pg_prop_fail(tc, "connect failed: %s", err ? err : "");

	initStringInfo(&a);
	initStringInfo(&b);
	draw_obj(tc, &a, na);
	draw_obj(tc, &b, nb);

	initStringInfo(&q);
	appendStringInfo(&q, "SELECT (%s || %s) @> %s", a.data, b.data, b.data);

	require_true(tc, conn, q.data);

	pfree(a.data);
	pfree(b.data);
	pfree(q.data);
	pg_prop_disconnect(conn);
}

/*
 * Containment is transitive: A @> B and B @> C imply A @> C.  Built from
 * J so the hypotheses hold by construction: A = J (full, nkeys >= 2), B = a
 * two-key projection {k0,k1} of J, C = a one-key projection {k0} of J.  Each
 * projection takes J's own values, so A @> B, B @> C and the implied A @> C
 * must all be true.
 */
PG_PROP(contains_transitive)
{
	pg_prop_conn *conn;
	char	   *err = NULL;
	int			n = (int) pg_prop_draw_int(tc, 2, 4);
	StringInfoData j,
				q;

	conn = pg_prop_connect(&err);
	if (conn == NULL)
		pg_prop_fail(tc, "connect failed: %s", err ? err : "");

	initStringInfo(&j);
	draw_obj(tc, &j, n);

	/*
	 * A = J; B = {k0,k1} projection; C = {k0} projection.  Assert all three
	 * containments including the transitively implied A @> C in one SELECT.
	 */
	initStringInfo(&q);
	appendStringInfo(&q,
					 "SELECT (%s @> jsonb_build_object('k0', %s -> 'k0', 'k1', %s -> 'k1')) "
					 "AND (jsonb_build_object('k0', %s -> 'k0', 'k1', %s -> 'k1') "
					 "@> jsonb_build_object('k0', %s -> 'k0')) "
					 "AND (%s @> jsonb_build_object('k0', %s -> 'k0'))",
					 j.data, j.data, j.data,
					 j.data, j.data, j.data,
					 j.data, j.data);

	require_true(tc, conn, q.data);

	pfree(j.data);
	pfree(q.data);
	pg_prop_disconnect(conn);
}

/*-------------------------------------------------------------------------
 *
 * prop_jsonbcontain.c
 *	  Property-based tests for jsonb containment and key-existence operators
 *	  (src/backend/utils/adt/jsonb_op.c, jsonb_util.c).
 *
 * jsonb's containment (@>, <@) and key-existence (?, ?|, ?&) operators form a
 * small algebra over objects: a value contains itself, contains any projection
 * of its own keys, and contains the empty object; a key test is true exactly
 * when the key is present; and containment is transitive and survives concat.
 * The oracle here is that algebra -- every property is a SELECT of a boolean
 * that must be "t" for every generated object, so a "f" (or a NULL/error on
 * finite valid input) is a bug in a containment or existence operator.
 *
 * Distinct from prop_jsonbops.c (the ||, - and #- mutation operators) and
 * prop_jsonb.c / prop_jsonbuild.c / prop_jsonpath.c (text round-trips,
 * builders, path queries): this area targets @>, <@, ?, ?| and ?&.
 *
 * Tier B: runs SQL against the cluster the TAP driver started; see
 * pg_prop.h and t/002_sql_props.pl.
 *
 * Copyright (c) 2026, PostgreSQL Global Development Group
 *
 * IDENTIFICATION
 *	  src/test/prop/prop_jsonbcontain.c
 *
 *-------------------------------------------------------------------------
 */
#include "postgres_fe.h"

#define PG_PROP_AREA "jsonbcontain"
#include "pg_prop.h"

#include "lib/stringinfo.h"

/*
 * Build a jsonb object literal '{"k0":v0,"k1":v1,...}' with nkeys members into
 * buf.  Keys are generated by index (k0, k1, ...) so they are distinct and
 * none are dropped by jsonb's last-wins dedup; each value is a drawn small
 * integer.  Integer values carry no quote/backslash hazard, so the whole token
 * drops into a single-quoted SQL literal with no escaping.  The result is a
 * complete single-quoted token with the ::jsonb cast.
 */
static void
draw_obj(pg_prop_tc *tc, StringInfo buf, int nkeys)
{
	appendStringInfoString(buf, "'{");
	for (int i = 0; i < nkeys; i++)
	{
		if (i > 0)
			appendStringInfoChar(buf, ',');
		appendStringInfo(buf, "\"k%d\":%d", i,
						 (int) pg_prop_draw_int(tc, -1000, 1000));
	}
	appendStringInfoString(buf, "}'::jsonb");
}

/*
 * Run a boolean-valued SELECT and require it to return "t".  A NULL result or
 * a SQL error means a containment/existence operator errored or produced NULL
 * on finite valid input, which is itself a bug -- so either is a failure,
 * reported with the SQL.
 */
static void
require_true(pg_prop_tc *tc, pg_prop_conn *conn, const char *sql)
{
	bool		failed = false;
	char	   *err = NULL;
	char	   *res;

	res = pg_prop_sql_scalar(conn, sql, &failed, &err);
	if (failed)
	{
		pg_prop_fail(tc, "SQL error for: %s\n  error: %s",
					 sql, err ? err : "(unknown)");
	}
	if (res == NULL)
	{
		pg_prop_fail(tc, "unexpected NULL result for: %s", sql);
	}
	if (strcmp(res, "t") != 0)
	{
		pg_prop_fail(tc, "invariant failed (got %s) for: %s", res, sql);
	}
	pg_free(res);
	if (err)
		pg_free(err);
}

/*
 * A value contains itself in both directions: J @> J AND J <@ J.  Containment
 * is reflexive, so this must hold for every object regardless of its keys.
 */
PG_PROP(contains_self)
{
	pg_prop_conn *conn;
	char	   *err = NULL;
	int			n = (int) pg_prop_draw_int(tc, 1, 4);
	StringInfoData j,
				q;

	conn = pg_prop_connect(&err);
	if (conn == NULL)
		pg_prop_fail(tc, "connect failed: %s", err ? err : "");

	initStringInfo(&j);
	draw_obj(tc, &j, n);

	initStringInfo(&q);
	appendStringInfo(&q, "SELECT (%s @> %s) AND (%s <@ %s)",
					 j.data, j.data, j.data, j.data);

	require_true(tc, conn, q.data);

	pfree(j.data);
	pfree(q.data);
	pg_prop_disconnect(conn);
}


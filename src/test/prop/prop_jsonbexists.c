/*-------------------------------------------------------------------------
 *
 * prop_jsonbexists.c
 *	  Property-based tests for the jsonb existence operators ?, ?| and ?&.
 *
 * The existence operators probe presence, not value: J ? k is true exactly
 * when k is a top-level object key (or, for an array, a string element); ?|
 * is "any of these present" and ?& is "all of these present".  The oracle is
 * that presence algebra over objects built with distinct keys k0..k(n-1) and
 * over jsonb string arrays: a present key tests true, an absent key tests
 * false, "any" needs one hit, "all" needs every hit, and both quantifiers over
 * an empty key list are false.  Every property is a SELECT of a boolean that
 * must be "t"; a "f" (or a NULL/error on finite valid input) is a bug in ?,
 * ?| or ?&.
 *
 * Distinct from prop_jsonbcontain.c (the @>/<@ containment algebra) and
 * prop_jsonbkeys.c (iterator/extraction cross-checks): this area targets only
 * the three existence operators, including their behaviour on string arrays
 * and on an empty key list.
 *
 * Tier B: runs SQL against the cluster the TAP driver started; see
 * pg_prop.h and t/002_sql_props.pl.
 *
 * Copyright (c) 2026, PostgreSQL Global Development Group
 *
 * IDENTIFICATION
 *	  src/test/prop/prop_jsonbexists.c
 *
 *-------------------------------------------------------------------------
 */
#include "postgres_fe.h"

#define PG_PROP_AREA "jsonbexists"
#include "pg_prop.h"

#include "lib/stringinfo.h"

/*
 * Run a boolean-valued SELECT and require it to return "t".  A NULL result or
 * a SQL error means an existence operator errored or produced NULL on finite
 * valid input, which is itself a bug -- so either is a failure, reported with
 * the SQL.  (Same contract as prop_numeric.c's require_true.)
 */
static void
require_true(pg_prop_tc *tc, pg_prop_conn *conn, const char *sql)
{
	bool		failed = false;
	char	   *err = NULL;
	char	   *res;

	res = pg_prop_sql_scalar(conn, sql, &failed, &err);
	if (failed)
	{
		pg_prop_fail(tc, "SQL error for: %s\n  error: %s",
					 sql, err ? err : "(unknown)");
	}
	if (res == NULL)
	{
		pg_prop_fail(tc, "unexpected NULL result for: %s", sql);
	}
	if (strcmp(res, "t") != 0)
	{
		pg_prop_fail(tc, "invariant failed (got %s) for: %s", res, sql);
	}
	pg_free(res);
	if (err)
		pg_free(err);
}

/*
 * Build a jsonb object literal '{"k0":v0,...,"k(n-1):v(n-1)"}' with n distinct
 * keys into buf.  Keys are generated by index (k0, k1, ...) so they are
 * distinct and never equal the literal 'absent' names used below; each value
 * is a drawn small integer, which carries no quote/backslash hazard, so the
 * whole token drops into a single-quoted SQL literal with no escaping.  The
 * result is a complete single-quoted token with the ::jsonb cast.
 */
static void
draw_obj(pg_prop_tc *tc, StringInfo buf, int nkeys)
{
	appendStringInfoString(buf, "'{");
	for (int i = 0; i < nkeys; i++)
	{
		if (i > 0)
			appendStringInfoChar(buf, ',');
		appendStringInfo(buf, "\"k%d\":%d", i,
						 (int) pg_prop_draw_int(tc, -1000, 1000));
	}
	appendStringInfoString(buf, "}'::jsonb");
}

/*
 * Build a jsonb array literal of n distinct strings "s0".."s(n-1)" into buf.
 * The element names are ASCII "s<i>" so they need no quote-escaping and never
 * collide with the object key names; the first element is always 's0' so the
 * array-element existence probe below is never vacuous.  Returns a complete
 * single-quoted token with the ::jsonb cast.
 */
static void
draw_str_array(StringInfo buf, int nelem)
{
	appendStringInfoString(buf, "'[");
	for (int i = 0; i < nelem; i++)
	{
		if (i > 0)
			appendStringInfoChar(buf, ',');
		appendStringInfo(buf, "\"s%d\"", i);
	}
	appendStringInfoString(buf, "]'::jsonb");
}

/*
 * Property 1 -- key_exists_present: with k0 present (nkeys >= 1), J ? 'k0' is
 * true.  The ? operator must report a present top-level key as existing.
 */
PG_PROP(key_exists_present)
{
	pg_prop_conn *conn;
	char	   *err = NULL;
	int			n = (int) pg_prop_draw_int(tc, 1, 4);
	StringInfoData j,
				q;

	conn = pg_prop_connect(&err);
	if (conn == NULL)
		pg_prop_fail(tc, "connect failed: %s", err ? err : "");

	initStringInfo(&j);
	draw_obj(tc, &j, n);

	initStringInfo(&q);
	appendStringInfo(&q, "SELECT %s ? 'k0'", j.data);

	require_true(tc, conn, q.data);

	pfree(j.data);
	pfree(q.data);
	pg_prop_disconnect(conn);
}

